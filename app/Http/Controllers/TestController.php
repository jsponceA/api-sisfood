    public function setearTodosDesayunos()
    {
        $ventas = Sale::query()
            ->whereHas("saleDetails",function ($q){
                $q->where("product_name","DESAYUNO");
            })
            ->get();

        foreach ($ventas as $venta) {
            $s = Sale::query()->findOrFail($venta->id);
            $s->total_sale = 4.20;
            $s->total_igv = 4.20;
            $s->total_dsct_form = 4.20;
            $s->total_pay_company = 0;
            $s->update();
        }
    }

